"""The two opt-in integration points, and the only places a review may alter a run.

Both hooks run after the raw model response has already been written to disk and before
the validator that would turn a clarification into a stop. With the review off, neither
hook is called and both arms behave exactly as before.

What a review may and may not do:

* It may turn one *unresolved* proposal into a bound one, and only when exactly one
  candidate matched every asserted condition with no unexcluded competitor.
* It never touches a proposal the model already bound. A model that answered is not
  second-guessed by a lexical reviewer.
* It never repairs a document that violates a contract. If the original evidence is over
  budget, or its question is missing, or its candidate list is malformed, or it names an
  inactive id, the original is passed through untouched and fails its own checks. That is
  decided by running the unchanged ``room_plan.validate_current_binding`` on the raw
  proposal against the real scene documents, not by a cheaper look-alike check, and there
  is no setting that turns the behaviour off.
* A revised proposal is handed to the unchanged validator, not around it.
* In the control arm it is record-only. A stopped prebinding document carries no visit
  order, and the visit order is not something source facts can supply, so a recovered
  role is reported as a binding recovery with the run still stopped. Nothing invents the
  ordering to make a document look complete.
"""

import copy

from . import REVIEW_VERSION, MODE_OFF, MODE_EVIDENCE_ONLY, MODE_EVIDENCE_PLUS_COSINE, MODES
from . import evidence as evidence_module
from . import lexical_cosine
from ..contracts import text_budget
from ..room_recursive import room_plan

HOOK_VERSION = "candidate_review_hooks_v1_20261107"
#: The statuses a review is allowed to look at. A bound proposal is left alone.
UNRESOLVED_STATUSES = ("ambiguous", "needs_environment_context",
                       "missing_environment_information", "missing_user_information")
#: Why a recovery is not a completed anything: the binding was recovered and everything
#: downstream of it remains unrun.
RECOVERY_SCOPE = "binding_recovered_downstream_pending"


def _cosine_for(mode):
    return lexical_cosine if mode == MODE_EVIDENCE_PLUS_COSINE else None


def _check_mode(mode):
    if mode not in MODES:
        raise ValueError("Unknown review mode " + repr(mode))
    return mode


def _candidate_budgets(proposal):
    """Measure every per-candidate ``why_still_fits`` field, not only the main evidence.

    Measurement only since evidence_audit_log_v1: no field is refused for its length.
    An ambiguous answer puts most of its prose here, so measuring only the top-level
    evidence field would under-report the raw document.
    """
    rows = []
    items = (proposal or {}).get("candidate_evidence") if isinstance(proposal, dict) else None
    for position, item in enumerate(items or []):
        text = item.get("why_still_fits") if isinstance(item, dict) else None
        rows.append({
            "position": position,
            "object_id": item.get("object_id") if isinstance(item, dict) else None,
            "field": "candidate_evidence[" + str(position) + "].why_still_fits",
            "budget": text_budget.measure(text) if isinstance(text, str) else None,
            "field_is_not_a_string": not isinstance(text, str)})
    return rows


def _program_evidence(record, object_id):
    """Short, program-generated evidence for a recovered binding.

    It names the conditions and the source paths the recovery rests on. It is marked as
    program-generated wherever it is stored, and the model's own prose is kept verbatim
    in the review record rather than being edited into this one.
    """
    row = next((item for item in record["candidate_rows"]
                if item["object_id"] == object_id), None)
    conditions = [item["condition"] for item in (row or {}).get("conditions", [])]
    return ("Program-generated by " + REVIEW_VERSION + ". Object " + str(object_id)
            + " is the only candidate in the supplied graph matching every asserted "
            "condition (" + ", ".join(conditions) + "); every other candidate carries a "
            "contradiction with a named source path. Source annotations only; not "
            "perception truth.")


#: The one validator that decides whether a raw proposal already honours its contract.
ORIGINAL_CONTRACT_VALIDATOR = "embodied_pipeline.room_recursive.room_plan.validate_current_binding"


def _raw_contract_validation(proposal, visit, scene):
    """Run the unchanged binding validator over the model's own raw proposal.

    This is the full validator, on the real scene nodes and overlay, so every check it
    makes is made here too: contract fields (evidence optional), the visit it belongs
    to, integer and active source ids, distinct candidates, per-candidate evidence
    shape, the question format, and the status-specific rules
    such as "an unresolved binding needs a concrete question" and "a bound object with a
    recorded room must not carry one".

    A cheaper keys-and-budget check was not enough: a raw ``ambiguous`` proposal with a
    null question, or with a single candidate, would have passed it and then been rewritten
    into a ``bound`` proposal, which would have hidden the original contract defect behind
    a source review. Nothing here is configurable.

    This runs on every reviewed proposal, not only on the ones a recovery was about to
    replace. Under strict evidence most decisions are not recoveries, and while this
    check only ran in the recovery branch the raw document's own contract result was
    absent from the record for every other decision: a response with tidy evidence but
    a null question read exactly like a clean one. Evidence length is measured only and
    is never a refusal condition since evidence_audit_log_v1. Those are
    two different findings, so both are recorded for every proposal and an invalid raw
    proposal is never revised whatever the decision was.

    Returns the record itself. ``detail`` carries the validator's own refusal text and
    ``diagnostics`` its measurement, if it attached one, so the defect is reported
    rather than silently absorbed.
    """
    inputs = (scene or {}).get("validator_inputs")
    base = {"validator": ORIGINAL_CONTRACT_VALIDATOR,
            "scope": "the full unchanged validator on the real scene nodes and overlay",
            "no_setting_bypasses_this": True,
            "recorded_for_every_decision": True,
            "model_evidence_text_used_as_source_fact": False}
    if not isinstance(inputs, dict) or not inputs.get("nodes") or not inputs.get("overlay"):
        return {**base, "revalidated": False, "passed": False, "error_type": None,
                "detail": None, "diagnostics": None,
                "refusal": ("the scene carries no read-only validator inputs, so the "
                            "original proposal cannot be re-validated and is therefore "
                            "not replaced")}
    try:
        room_plan.validate_current_binding(copy.deepcopy(proposal), visit,
                                           inputs["nodes"], inputs["overlay"])
    except (room_plan.PlanRefused, ValueError, TypeError, KeyError, IndexError) as exc:
        return {**base, "revalidated": True, "passed": False,
                "error_type": type(exc).__name__, "detail": str(exc),
                "diagnostics": getattr(exc, "diagnostics", None),
                "refusal": ("the original proposal does not pass the unchanged binding "
                            "validator, so it stands and fails its own check rather than "
                            "being replaced by a review")}
    return {**base, "revalidated": True, "passed": True, "error_type": None,
            "detail": None, "diagnostics": None, "refusal": None}


def review_visit_proposal(proposal, visit, plan, scene, mode=MODE_EVIDENCE_ONLY,
                          config=None):
    """Recursive arm: review one bind-next proposal before it is validated.

    Returns ``(record, revised_proposal_or_None)``. A ``None`` revision means the
    original proposal travels on untouched, which is the default for every decision
    other than a single surviving candidate.
    """
    _check_mode(mode)
    settings = dict(evidence_module.DEFAULT_CONFIG)
    settings.update(config or {})
    need = {"kind": "visit", "id": visit.get("visit_event_id"),
            "phrase": visit.get("phrase"),
            "instruction": (plan or {}).get("original_instruction"),
            "proposal": proposal}
    record = evidence_module.review_need(need, scene, mode=mode, config=settings,
                                         cosine=_cosine_for(mode))
    record["hook_version"] = HOOK_VERSION
    record["arm"] = "room_recursive"
    record["integration_point"] = "after bind_next raw response, before validate_current_binding"
    record["applies_only_to_unresolved_proposals"] = True
    record["recovery_scope"] = RECOVERY_SCOPE
    record["original_candidate_evidence_budgets"] = _candidate_budgets(proposal)
    validation = _raw_contract_validation(proposal, visit, scene)
    record["raw_contract_validation"] = {
        key: value for key, value in validation.items() if key != "refusal"}
    status = proposal.get("status") if isinstance(proposal, dict) else None
    record["original_status"] = status
    if status not in UNRESOLVED_STATUSES:
        record["change_reason"] = ("the model bound this target itself, so the review is "
                                   "recorded for comparison and changes nothing")
        return record, None
    if record["decision"] != evidence_module.AUTO_DISAMBIGUATED:
        record["change_reason"] = ("the review did not leave a single surviving candidate, so "
                                   "the model's own answer and its question stand unchanged")
        return record, None
    passed = validation["passed"]
    detail = ({"error_type": validation["error_type"], "error": validation["detail"],
               "diagnostics": validation["diagnostics"]}
              if validation["revalidated"] and not passed else None)
    record["original_contract_check"] = {
        "validator": ORIGINAL_CONTRACT_VALIDATOR, "passed": passed, "detail": detail,
        "scope": "the full unchanged validator on the real scene nodes and overlay",
        "no_setting_bypasses_this": True}
    if not passed:
        record["change_reason"] = validation["refusal"]
        record["original_defect_preserved"] = True
        return record, None
    object_id = record["full_match_object_ids"][0]
    row = scene["rows"][object_id]
    if row["region_status"] != "assigned":
        record["change_reason"] = ("the surviving candidate has no recorded room, so the "
                                   "environment stop is left in place rather than bound to "
                                   "an unrecorded room")
        return record, None
    revised = copy.deepcopy(proposal)
    revised.update({
        "status": "bound",
        "object_id": object_id,
        "region_id": row["region_id"],
        "candidate_object_ids": [],
        "candidate_evidence": [],
        "clarification_question": None,
        "evidence": _program_evidence(record, object_id),
    })
    record["changed"] = True
    record["revised_proposal"] = revised
    record["revised_proposal_is_program_generated"] = True
    record["model_clarification_question_discarded_but_retained_here"] = \
        proposal.get("clarification_question")
    record["change_reason"] = ("one candidate survived every asserted condition, so the "
                               "clarification was not needed. The revised proposal is "
                               "validated by the unchanged validator, not around it.")
    return record, revised


def review_prebinding_document(document, instruction, scene, mode=MODE_EVIDENCE_ONLY,
                               config=None):
    """Control arm: review every unresolved role before ``validate_prebinding``.

    Record-only by construction. A stopped prebinding document carries no visit order,
    and no source fact supplies one, so this hook never rewrites the document into a
    runnable one. It reports, per role, whether the question the model asked was needed.
    """
    _check_mode(mode)
    settings = dict(evidence_module.DEFAULT_CONFIG)
    settings.update(config or {})
    roles = document.get("roles") if isinstance(document, dict) else None
    reviews = []
    for role in roles or []:
        status = role.get("status")
        proposal = {"status": status, "object_id": role.get("object_id"),
                    "candidate_object_ids": role.get("candidate_object_ids") or [],
                    "evidence": role.get("evidence"),
                    "clarification_question": role.get("clarification_question")}
        need = {"kind": "role", "id": role.get("role_id"), "phrase": role.get("role_text"),
                "instruction": instruction, "proposal": proposal}
        record = evidence_module.review_need(need, scene, mode=mode, config=settings,
                                             cosine=_cosine_for(mode))
        record["hook_version"] = HOOK_VERSION
        record["arm"] = "topology_cropped"
        record["integration_point"] = ("after prebinding_raw.json is frozen, before "
                                       "validate_prebinding")
        record["original_status"] = status
        record["applies_only_to_unresolved_proposals"] = True
        record["recovery_scope"] = RECOVERY_SCOPE
        record["original_candidate_evidence_budgets"] = _candidate_budgets(role)
        record["per_candidate_evidence_field_exists_on_this_wire"] = isinstance(
            role.get("candidate_evidence"), list)
        if status not in UNRESOLVED_STATUSES:
            record["change_reason"] = ("the model bound this role itself, so the review is "
                                       "recorded for comparison and changes nothing")
        elif record["decision"] == evidence_module.AUTO_DISAMBIGUATED:
            record["binding_recovered"] = True
            record["document_still_stops"] = True
            record["change_reason"] = (
                "one candidate survived every asserted condition, so this role's question "
                "was not needed. The document still stops: a stopped prebinding carries no "
                "visit order, and no source fact supplies one, so nothing here completes "
                "the document or claims the task would have run.")
        else:
            record["change_reason"] = ("the review did not leave a single surviving "
                                       "candidate, so this role's question stands")
        reviews.append(record)
    return {
        "review_version": REVIEW_VERSION, "hook_version": HOOK_VERSION,
        "mode": mode, "arm": "topology_cropped",
        "document_was_modified": False,
        "document_modification_is_not_implemented_because":
            "a stopped prebinding document carries no visit order and this reviewer does "
            "not invent one",
        "role_reviews": reviews,
        "roles_with_recovered_binding": [item["need"]["id"] for item in reviews
                                         if item.get("binding_recovered")],
        "recovery_scope": RECOVERY_SCOPE,
    }


def scene_from_inputs(nodes, overlay, edges=None):
    """Convenience wrapper so a caller does not reach into :mod:`evidence` directly."""
    return evidence_module.prepare_scene(nodes, overlay, edges)


